async function getGuildSettings(guildId) {
  const hit = cache.get(guildId);
  if (hit && Date.now() - hit.at < CACHE_TTL_MS) return hit.settings;
  let settings = { ...DEFAULTS };
  if (db.isEnabled()) {
    const rows = await db.query(`SELECT ${COLUMNS.join(', ')} FROM guild_settings WHERE guild_id = ?`, [guildId]);
    if (rows?.length) {
      const r = rows[0];
      let statChannels = {};
      try { statChannels = r.server_stats_channels ? JSON.parse(r.server_stats_channels) : {}; } catch {}
      settings = {
        welcomeChannelId: r.welcome_channel_id || '',
        welcomeMessage: r.welcome_message || DEFAULT_WELCOME_MESSAGE,
        welcomeEnabled: r.welcome_enabled !== 0,
        goodbyeChannelId: r.goodbye_channel_id || '',
        goodbyeMessage: r.goodbye_message || DEFAULT_GOODBYE_MESSAGE,
        goodbyeEnabled: r.goodbye_enabled !== 0,
        suggestionChannelId: r.suggestion_channel_id || '',
        logChannelId: r.log_channel_id || '',
        ticketCategoryId: r.ticket_category_id || '',
        ticketLogChannelId: r.ticket_log_channel_id || '',
        ticketSupportRoleId: r.ticket_support_role_id || '',
        serverStatsEnabled: Boolean(r.server_stats_enabled),
        serverStatsChannels: statChannels,
        warnThreshold: r.warn_threshold,
        warnAction: r.warn_action,
        djRoleId: r.dj_role_id || '',
        embedColor: r.embed_color || '',
        ticketPanelChannelId: r.ticket_panel_channel_id || '',
        levelUpMessages: r.level_up_messages !== 0,
        levelRoles: (() => { try { return r.level_roles ? JSON.parse(r.level_roles) : {}; } catch { return {}; } })(),
        liveChannelNameTemplate: r.live_channel_name_template || '',
        applicationReviewerRoleId: r.application_reviewer_role_id || '',
        inviteLogChannelId: r.invite_log_channel_id || '',
        inviteMinAccountAgeDays: r.invite_min_account_age_days,
        botThreshold: r.bot_threshold,
        botAutoAction: r.bot_auto_action || 'flag',
        botSuspectRoleId: r.bot_suspect_role_id || '',
        verificationEnabled: r.verification_enabled === 1,
        verificationChannelId: r.verification_channel_id || '',
        verificationRoleId: r.verification_role_id || '',
        verificationMode: r.verification_mode || 'button',
        verificationPanelMessageId: r.verification_panel_message_id || '',
        tempvcCreateChannelId: r.tempvc_create_channel_id || '',
        tempvcCategoryId: r.tempvc_category_id || '',
        birthdayChannelId: r.birthday_channel_id || '',
        birthdayAnnounceHour: r.birthday_announce_hour ?? 9,
        bumpChannelId: r.bump_channel_id || '',
        defaultWeatherLocation: r.default_weather_location || '',
        weatherUnits: r.weather_units || 'imperial',
        welcomeImageEnabled: r.welcome_image_enabled === 1,
        welcomeImageOnly: r.welcome_image_only === 1,
        aiEnabled: r.ai_enabled === 1,
        aiChannelId: r.ai_channel_id || '',
        modmailEnabled: r.modmail_enabled === 1,
        modmailCategoryId: r.modmail_category_id || '',
        voiceXpPerMinute: r.voice_xp_per_minute ?? null,
        mediaChannels: (() => { try { return r.media_channels ? JSON.parse(r.media_channels) : []; } catch { return []; } })(),
        ghostpingEnabled: r.ghostping_enabled === 1,
        ghostpingChannelId: r.ghostping_channel_id || '',
        threadArchiveMinutes: r.thread_archive_minutes ?? 1440,
        confessionsEnabled: r.confessions_enabled === 1,
        confessionsChannelId: r.confessions_channel_id || '',
        confessionsRequireApproval: r.confessions_require_approval !== 0,
        birthdayRoleId: r.birthday_role_id || '',
        streakBonusPerDay: r.streak_bonus_per_day ?? 25,
        streakMilestoneBonuses: (() => { try { return r.streak_milestone_bonuses ? JSON.parse(r.streak_milestone_bonuses) : { '7': 'Common Crate', '30': 'Rare Crate', '100': 'Legendary Crate' }; } catch { return { '7': 'Common Crate', '30': 'Rare Crate', '100': 'Legendary Crate' }; } })(),
        djEnabled: r.dj_enabled === 1,
        djOnlySkip: r.dj_only_skip !== 0,
        prestigeRoleId: r.prestige_role_id || '',
        music247Enabled: r.music247_enabled === 1,
        music247ChannelId: r.music247_channel_id || '',
        boosterRoleId: r.booster_role_id || '',
        robberyEnabled: r.robbery_enabled !== 0,
        newMemberLinkEnabled: r.new_member_link_enabled === 1,
        newMemberLinkDays: r.new_member_link_days ?? 7,
        welcomeDmEnabled: r.welcome_dm_enabled === 1,
        welcomeDmMessage: r.welcome_dm_message || '',
        lotteryTicketPrice: r.lottery_ticket_price ?? 100,
        lotteryChannelId: r.lottery_channel_id || '',
        antinukeEnabled: r.antinuke_enabled === 1,
        antinukeAction: r.antinuke_action || 'kick',
        antinukeThreshold: r.antinuke_threshold ?? 5,
        antinukeLogChannelId: r.antinuke_log_channel_id || '',
        antinukeWhitelistRoles: (() => { try { const v = r.antinuke_whitelist_roles; return Array.isArray(v) ? v : (v ? JSON.parse(v) : []); } catch { return []; } })(),
        afkVoiceEnabled: r.afk_voice_enabled === 1,
        afkVoiceMinutes: r.afk_voice_minutes ?? 30,
        afkVoiceChannelId: r.afk_voice_channel_id || '',
        afkVoiceExemptRoleId: r.afk_voice_exempt_role_id || '',
        imageStarboardChannelId: r.image_starboard_channel_id || '',
        imageStarboardThreshold: r.image_starboard_threshold ?? 3,
        levelupChannelId: r.levelup_channel_id || '',
        afkAutocreateEnabled: r.afk_autocreate_enabled === 1,
        afkChannelId: r.afk_channel_id || '',
        afkMaxUsers: r.afk_max_users ?? 10,
        autopublishChannels: (() => { try { const v = r.autopublish_channels; return Array.isArray(v) ? v : (v ? JSON.parse(v) : []); } catch { return []; } })(),
        reengageEnabled: r.reengage_enabled === 1,
        reengageDays: r.reengage_days ?? 30,
        reengageChannelId: r.reengage_channel_id || '',
        ticketButtonLabel: r.ticket_button_label || '',
        prefix: r.prefix || '',
      };
    }
  }
  // Legacy fallback: a single welcome channel from config.json.
  if (!settings.welcomeChannelId && config.welcomeChannelId) settings.welcomeChannelId = config.welcomeChannelId;
  cache.set(guildId, { settings, at: Date.now() });
  return settings;
}

async function setGuildSettings(guildId, patch) {
  const current = await getGuildSettings(guildId);
  const next = { ...current, ...patch };
  cache.set(guildId, { settings: next, at: Date.now() });
  if (!db.isEnabled()) return { saved: false, settings: next };
  const values = [
    next.welcomeChannelId || null, next.welcomeMessage || null, next.welcomeEnabled ? 1 : 0,
    next.goodbyeChannelId || null, next.goodbyeMessage || null, next.goodbyeEnabled ? 1 : 0,
    next.suggestionChannelId || null,
    next.logChannelId || null, next.ticketCategoryId || null, next.ticketLogChannelId || null,
    next.ticketSupportRoleId || null,
    next.warnThreshold ?? null, next.warnAction || null, next.djRoleId || null,
    next.embedColor || null, next.ticketPanelChannelId || null,
    next.levelUpMessages ? 1 : 0, JSON.stringify(next.levelRoles || {}),
    next.serverStatsEnabled ? 1 : 0, JSON.stringify(next.serverStatsChannels || {}),
    next.liveChannelNameTemplate || null,
    next.applicationReviewerRoleId || null,
    next.inviteLogChannelId || null,
    next.inviteMinAccountAgeDays ?? null,
    next.botThreshold ?? null,
    next.botAutoAction || 'flag',
    next.botSuspectRoleId || null,
    next.verificationEnabled ? 1 : 0,
    next.verificationChannelId || null,
    next.verificationRoleId || null,
    next.verificationMode || 'button',
    next.verificationPanelMessageId || null,
    next.tempvcCreateChannelId || null,
    next.tempvcCategoryId || null,
    next.birthdayChannelId || null,
    next.birthdayAnnounceHour ?? 9,
    next.bumpChannelId || null,
    next.defaultWeatherLocation || null,
    next.weatherUnits || 'imperial',
    next.welcomeImageEnabled ? 1 : 0,
    next.welcomeImageOnly ? 1 : 0,
    next.aiEnabled ? 1 : 0,
    next.aiChannelId || null,
    next.modmailEnabled ? 1 : 0,
    next.modmailCategoryId || null,
    next.voiceXpPerMinute ?? null,
    JSON.stringify(next.mediaChannels || []),
    next.ghostpingEnabled ? 1 : 0,
    next.ghostpingChannelId || null,
    next.threadArchiveMinutes ?? 1440,
    next.confessionsEnabled ? 1 : 0,
    next.confessionsChannelId || null,
    next.confessionsRequireApproval ? 1 : 0,
    next.birthdayRoleId || null,
    next.streakBonusPerDay ?? 25,
    JSON.stringify(next.streakMilestoneBonuses || { '7': 'Common Crate', '30': 'Rare Crate', '100': 'Legendary Crate' }),
    next.djEnabled ? 1 : 0,
    next.djOnlySkip ? 1 : 0,
    next.prestigeRoleId || null,
    next.music247Enabled ? 1 : 0,
    next.music247ChannelId || null,
    next.boosterRoleId || null,
    next.robberyEnabled ? 1 : 0,
    next.newMemberLinkEnabled ? 1 : 0,
    next.newMemberLinkDays ?? 7,
    next.welcomeDmEnabled ? 1 : 0,
    next.welcomeDmMessage || null,
    next.lotteryTicketPrice ?? 100,
    next.lotteryChannelId || null,
    next.antinukeEnabled ? 1 : 0,
    next.antinukeAction || 'kick',
    next.antinukeThreshold ?? 5,
    next.antinukeLogChannelId || null,
    JSON.stringify(next.antinukeWhitelistRoles || []),
    next.afkVoiceEnabled ? 1 : 0,
    next.afkVoiceMinutes ?? 30,
    next.afkVoiceChannelId || null,
    next.afkVoiceExemptRoleId || null,
    next.imageStarboardChannelId || null,
    next.imageStarboardThreshold ?? 3,
    next.levelupChannelId || null,
    next.afkAutocreateEnabled ? 1 : 0,
    next.afkChannelId || null,
    next.afkMaxUsers ?? 10,
    JSON.stringify(next.autopublishChannels || []),
    next.reengageEnabled ? 1 : 0,
    next.reengageDays ?? 30,
    next.reengageChannelId || null,
    next.ticketButtonLabel || null,
    next.prefix || null,
  ];
  // COLUMNS.length columns, values.length params — keep them in sync.
  if (values.length !== COLUMNS.length) throw new Error(`guildSettings column/param mismatch: ${COLUMNS.length} columns, ${values.length} values`);
  await db.query(
    `INSERT INTO guild_settings (guild_id, ${COLUMNS.join(', ')})
     VALUES (?, ${COLUMNS.map(() => '?').join(', ')})
     ON DUPLICATE KEY UPDATE ${COLUMNS.map((c) => `${c} = VALUES(${c})`).join(', ')}`,
    [guildId, ...values],
  );
  return { saved: true, settings: next };
}

function invalidate(guildId) { cache.delete(guildId); }

module.exports = { getGuildSettings, setGuildSettings, invalidate, DEFAULTS, DEFAULT_WELCOME_MESSAGE, DEFAULT_GOODBYE_MESSAGE };
